import React, { useState, useRef, useEffect } from 'react';
import {
  Award,
  Download,
  Eye,
  CheckCircle2,
  Circle,
  Copy,
  Check,
  FileText,
  ShieldCheck,
  Building2,
  Upload,
  AlertCircle,
  Clock,
  FileSignature
} from 'lucide-react';
import { toast } from 'sonner';
import { useAuth } from '../../context/AuthContext';
import { useData } from '../../context/DataContext';
import { agentAPI, formatApiError } from '../../utils/api';
import { getContractProgress } from '../../utils/onboarding';
import { Button } from '../ui/button';
import { Input } from '../ui/input';

const formatDate = (d) =>
  d ? new Date(d).toLocaleDateString('en-US', { day: 'numeric', month: 'short', year: 'numeric' }) : '—';

export const AgentAgreementSettings = () => {
  const { user, updateUser } = useAuth();
  const { viewAgentContractFile } = useData();

  const [copied, setCopied] = useState(false);
  const [signedFile, setSignedFile] = useState(null);
  const [uploading, setUploading] = useState(false);
  const fileInputRef = useRef(null);

  // Sync latest user profile on mount
  useEffect(() => {
    let cancelled = false;
    agentAPI
      .getMe()
      .then((res) => {
        if (!cancelled && res?.data) updateUser(res.data);
      })
      .catch(() => { });
    return () => {
      cancelled = true;
    };
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, []);

  const active = !!(user?.isActivated || user?.contractStatus === 'active');
  const certNumber = user?.eCertificateNumber || (user?.agentCode ? `QS-AGT-${user.agentCode}` : null);
  const status = user?.contractStatus || (active ? 'active' : 'not_issued');
  const contractFiles = (user?.contractDocuments || []).filter((f) => f.kind === 'issued');
  const signedContractFiles = (user?.contractDocuments || []).filter((f) => f.kind === 'signed');
  const latestContract = contractFiles[contractFiles.length - 1];
  const latestSigned = signedContractFiles[signedContractFiles.length - 1];
  const progress = getContractProgress(user);

  const handleCopyCertNumber = () => {
    if (!certNumber) return;
    navigator.clipboard.writeText(certNumber);
    setCopied(true);
    toast.success('Certificate number copied to clipboard');
    setTimeout(() => setCopied(false), 2000);
  };

  const handleDownloadCertificate = () => {
    if (!user?.eCertificateFile && !active) {
      toast.info('Your E-Certificate is being generated by QStudy Compliance.');
      return;
    }
    viewAgentContractFile(user?.id || user?._id, 'certificate');
  };

  const handleDownloadContract = (docId) => {
    if (!docId) return;
    viewAgentContractFile(user?.id || user?._id, docId);
  };

  const handleFilePick = (e) => {
    const file = e.target.files?.[0];
    if (file && file.size > 10 * 1024 * 1024) {
      toast.error('File size exceeds 10MB limit');
      e.target.value = '';
      return;
    }
    setSignedFile(file || null);
  };

  const handleUploadSignedContract = async () => {
    if (!signedFile) return;
    setUploading(true);
    try {
      const res = await agentAPI.uploadOwnSignedContract(signedFile);
      if (res?.data) updateUser(res.data);
      setSignedFile(null);
      if (fileInputRef.current) fileInputRef.current.value = '';
      toast.success('Signed agreement uploaded', {
        description: 'QStudy Compliance is verifying your document to generate your E-Certificate.'
      });
    } catch (error) {
      toast.error('Could not upload signed agreement', { description: formatApiError(error) });
    } finally {
      setUploading(false);
    }
  };

  return (
    <div className="bg-white border border-slate-200 rounded-2xl shadow-sm overflow-hidden" data-testid="agent-agreement-settings">
      {/* ── Tab Header (Standard Portal Style) ── */}
      <div className="px-5 sm:px-8 py-5 border-b border-slate-100 flex flex-col sm:flex-row sm:items-center justify-between gap-3">
        <div>
          <h2 className="text-lg font-bold text-[#111827] font-['Outfit']">
            E-Certificate &amp; Partnership Contract
          </h2>
          <p className="text-xs text-slate-500 mt-0.5">
            Official accreditation credentials and executed partnership agreement for your agency.
          </p>
        </div>
        {active ? (
          <span className="inline-flex items-center gap-1.5 px-3 py-1 rounded-full text-xs font-semibold bg-emerald-50 text-emerald-700 border border-emerald-200 shrink-0 self-start sm:self-center">
            <CheckCircle2 className="w-3.5 h-3.5 text-emerald-600" />
            Active Partner
          </span>
        ) : (
          <span className="inline-flex items-center gap-1.5 px-3 py-1 rounded-full text-xs font-semibold bg-amber-50 text-amber-700 border border-amber-200 shrink-0 self-start sm:self-center">
            <Clock className="w-3.5 h-3.5 text-amber-600" />
            Activation In Progress
          </span>
        )}
      </div>

      <div className="p-5 sm:p-8 space-y-6">
        {/* ── 1. Status Overview Card (Matching clean portal design) ── */}
        <div className="border border-slate-200 rounded-xl p-5 sm:p-6 bg-[#F9FAFB] space-y-4">
          <div className="flex flex-col sm:flex-row sm:items-start justify-between gap-4">
            <div className="flex items-start gap-3.5">
              <div className="w-10 h-10 rounded-xl bg-emerald-100 text-emerald-700 flex items-center justify-center shrink-0 mt-0.5">
                <Award className="w-5 h-5 text-emerald-600" />
              </div>
              <div>
                <div className="flex items-center gap-2 flex-wrap">
                  <h3 className="text-base font-bold text-[#111827] font-['Outfit']">
                    {active ? 'Your account is active' : 'Agent Agreement & Accreditation'}
                  </h3>
                  {certNumber && (
                    <span className="text-xs font-mono font-semibold text-[#042C53] bg-[#E6F1FB] border border-[#B5D4F4] px-2 py-0.5 rounded">
                      ID: {user?.agentCode || certNumber}
                    </span>
                  )}
                </div>
                <p className="text-xs sm:text-sm text-slate-500 mt-1">
                  {active
                    ? `E-Certificate ${certNumber || ''}${user?.activatedAt ? ` · active since ${formatDate(user.activatedAt)}` : ''}. You can submit students.`
                    : 'Download your issued agreement, sign it, and upload the signed copy to activate your account.'}
                </p>
              </div>
            </div>

            {certNumber && (
              <button
                type="button"
                onClick={handleCopyCertNumber}
                className="inline-flex items-center gap-1.5 text-xs text-slate-600 hover:text-[#042C53] border border-slate-200 bg-white hover:bg-slate-50 px-3 py-1.5 rounded-lg transition-colors shrink-0 self-start sm:self-center"
              >
                {copied ? <Check className="w-3.5 h-3.5 text-emerald-600" /> : <Copy className="w-3.5 h-3.5" />}
                <span>{copied ? 'Copied' : 'Copy Certificate #'}</span>
              </button>
            )}
          </div>

          {/* Progress Steps Checklist */}
          <div className="flex flex-wrap items-center gap-x-6 gap-y-2 pt-3 border-t border-slate-200/80 text-xs text-slate-600">
            <div className="flex items-center gap-1.5">
              {progress.contractIssued ? (
                <CheckCircle2 className="w-4 h-4 text-emerald-600 shrink-0" />
              ) : (
                <Circle className="w-4 h-4 text-slate-300 shrink-0" />
              )}
              <span className={progress.contractIssued ? 'font-medium text-slate-800' : 'text-slate-400'}>
                Contract issued
              </span>
            </div>
            <div className="flex items-center gap-1.5">
              {progress.contractSigned ? (
                <CheckCircle2 className="w-4 h-4 text-emerald-600 shrink-0" />
              ) : (
                <Circle className="w-4 h-4 text-slate-300 shrink-0" />
              )}
              <span className={progress.contractSigned ? 'font-medium text-slate-800' : 'text-slate-400'}>
                Signed contract uploaded
              </span>
            </div>
            <div className="flex items-center gap-1.5">
              {progress.eCertificateIssued ? (
                <CheckCircle2 className="w-4 h-4 text-emerald-600 shrink-0" />
              ) : (
                <Circle className="w-4 h-4 text-slate-300 shrink-0" />
              )}
              <span className={progress.eCertificateIssued ? 'font-medium text-slate-800' : 'text-slate-400'}>
                E-Certificate issued, account active
              </span>
            </div>
          </div>
        </div>

        {/* ── 2. Official Documents Grid ── */}
        <div>
          <div className="mb-3">
            <h3 className="text-sm font-bold text-[#111827] font-['Outfit']">Official Documents</h3>
            <p className="text-xs text-slate-500">Download or view your accredited documents at any time.</p>
          </div>

          <div className="grid grid-cols-1 md:grid-cols-2 gap-4">
            {/* Document 1: E-Certificate */}
            <div className="p-4 sm:p-5 rounded-xl border border-slate-200 bg-white hover:border-slate-300 transition-all flex flex-col justify-between space-y-4">
              <div className="flex items-start gap-3.5">
                <div className="w-10 h-10 rounded-xl bg-[#E6F1FB] text-[#042C53] flex items-center justify-center shrink-0">
                  <Award className="w-5 h-5" />
                </div>
                <div className="min-w-0 flex-1">
                  <div className="flex items-center gap-2 flex-wrap">
                    <span className="font-bold text-sm text-[#111827] truncate">
                      Authorized Partner E-Certificate
                    </span>
                    <span className="text-[10px] font-bold uppercase px-2 py-0.5 rounded bg-emerald-50 text-emerald-700 border border-emerald-200">
                      Accredited
                    </span>
                  </div>
                  <p className="text-xs text-slate-500 mt-1 leading-relaxed">
                    Official accreditation certifying your agency to counsel students and submit applications for partner universities.
                  </p>
                  {certNumber && (
                    <div className="text-[11px] font-mono text-slate-500 mt-2">
                      Cert No: <span className="font-bold text-[#042C53]">{certNumber}</span>
                    </div>
                  )}
                </div>
              </div>

              <div className="pt-3 border-t border-slate-100 flex flex-wrap items-center justify-between gap-2">
                <span className="text-[11px] font-medium text-slate-400">PDF Credential</span>
                <div className="flex items-center gap-2">
                  <Button
                    size="sm"
                    variant="outline"
                    onClick={handleDownloadCertificate}
                    disabled={!active && !user?.eCertificateFile}
                    className="h-8 text-xs hover:text-[#0C447C] font-medium text-slate-700  border-slate-200 hover:bg-slate-50 gap-1.5"
                  >
                    <Eye className="w-3.5 h-3.5 text-slate-500 hover:text-[#0C447C]" /> View
                  </Button>
                  <Button
                    size="sm"
                    onClick={handleDownloadCertificate}
                    disabled={!active && !user?.eCertificateFile}
                    className="h-8 text-xs font-semibold bg-[#042C53] hover:bg-[#0C447C] text-white gap-1.5"
                  >
                    <Download className="w-3.5 h-3.5" /> Download
                  </Button>
                </div>
              </div>
            </div>

            {/* Document 2: Issued Partnership Agreement */}
            <div className="p-4 sm:p-5 rounded-xl border border-slate-200 bg-white hover:border-slate-300 transition-all flex flex-col justify-between space-y-4">
              <div className="flex items-start gap-3.5">
                <div className="w-10 h-10 rounded-xl bg-slate-100 text-slate-700 flex items-center justify-center shrink-0">
                  <FileText className="w-5 h-5" />
                </div>
                <div className="min-w-0 flex-1">
                  <div className="flex items-center gap-2 flex-wrap">
                    <span className="font-bold text-sm text-[#111827] truncate">
                      Partnership Agreement (Contract)
                    </span>
                    <span className="text-[10px] font-bold uppercase px-2 py-0.5 rounded bg-blue-50 text-blue-700 border border-blue-200">
                      Official
                    </span>
                  </div>
                  <p className="text-xs text-slate-500 mt-1 leading-relaxed">
                    Recruitment partnership contract governing institutional terms, ethical standards, and commission schedules.
                  </p>
                  {latestContract?.uploadedAt && (
                    <div className="text-[11px] text-slate-400 mt-2">
                      Issued on {formatDate(latestContract.uploadedAt)}
                    </div>
                  )}
                </div>
              </div>

              <div className="pt-3 border-t border-slate-100 flex flex-wrap items-center justify-between gap-2">
                <span className="text-[11px] font-medium text-slate-400">PDF Agreement</span>
                {latestContract ? (
                  <Button
                    size="sm"
                    variant="outline"
                    onClick={() => handleDownloadContract(latestContract.id || latestContract._id)}
                    className="h-8 text-xs hover:text-[#0C447C] font-medium text-slate-700  border-slate-200 hover:bg-slate-50 gap-1.5"
                  >
                    <Download className="w-3.5 h-3.5 text-slate-500 hover:text-[#0C447C]" /> Download Contract
                  </Button>
                ) : (
                  <span className="text-xs text-slate-400 italic">Being prepared</span>
                )}
              </div>
            </div>

            {/* Document 3: Counter-Signed Copy (if available) */}
            {latestSigned && (
              <div className="p-4 sm:p-5 rounded-xl border border-slate-200 bg-white hover:border-slate-300 transition-all flex flex-col justify-between space-y-4 md:col-span-2">
                <div className="flex items-start gap-3.5">
                  <div className="w-10 h-10 rounded-xl bg-emerald-50 text-emerald-700 flex items-center justify-center shrink-0">
                    <ShieldCheck className="w-5 h-5" />
                  </div>
                  <div className="min-w-0 flex-1">
                    <div className="flex items-center gap-2 flex-wrap">
                      <span className="font-bold text-sm text-[#111827] truncate">
                        Signed Contract Copy
                      </span>
                      <span className="text-[10px] font-bold uppercase px-2 py-0.5 rounded bg-emerald-50 text-emerald-700 border border-emerald-200">
                        Executed
                      </span>
                    </div>
                    <p className="text-xs text-slate-500 mt-1 leading-relaxed">
                      Executed contract copy counter-signed by your agency authorized signatory.
                    </p>
                    {latestSigned?.uploadedAt && (
                      <div className="text-[11px] text-slate-400 mt-2">
                        Uploaded on {formatDate(latestSigned.uploadedAt)}
                      </div>
                    )}
                  </div>
                </div>

                <div className="pt-3 border-t border-slate-100 flex flex-wrap items-center justify-between gap-2">
                  <span className="text-[11px] font-medium text-slate-400">Verified Legal Copy</span>
                  <Button
                    size="sm"
                    variant="outline"
                    onClick={() => handleDownloadContract(latestSigned.id || latestSigned._id)}
                    className="h-8 text-xs font-medium text-slate-700 hover:text-[#0C447C] border-slate-200 hover:bg-slate-50 gap-1.5"
                  >
                    <Download className="w-3 h-3 text-slate-500 hover:text-[#0C447C]" /> Download Signed Copy
                  </Button>
                </div>
              </div>
            )}
          </div>
        </div>

        {/* ── 3. Upload Action (Only shown when contract is issued but unsigned) ── */}
        {!active && status === 'issued' && (
          <div className="p-5 border border-amber-200 rounded-xl bg-amber-50/50 space-y-3" data-testid="settings-contract-upload">
            <div className="flex items-start gap-3">
              <AlertCircle className="w-5 h-5 text-amber-600 mt-0.5 shrink-0" />
              <div>
                <h4 className="text-sm font-bold text-amber-950">Action Required: Upload Signed Agreement</h4>
                <p className="text-xs text-amber-800 mt-0.5 leading-relaxed">
                  Please download the issued contract above, sign the execution page, and upload the signed PDF copy below. Our compliance team will promptly review and issue your E-Certificate.
                </p>
              </div>
            </div>

            <div className="flex flex-col sm:flex-row items-stretch sm:items-center gap-3 pt-2">
              <Input
                ref={fileInputRef}
                type="file"
                accept=".pdf,.jpg,.jpeg,.png,.doc,.docx"
                onChange={handleFilePick}
                className="bg-white border-amber-200 text-xs flex-1"
              />
              <Button
                type="button"
                onClick={handleUploadSignedContract}
                disabled={!signedFile || uploading}
                className="bg-[#042C53] hover:bg-[#0C447C] text-white text-xs font-semibold h-10 px-5 rounded-lg shrink-0 gap-1.5"
              >
                <Upload className="w-4 h-4" />
                {uploading ? 'Uploading...' : 'Submit Signed Agreement'}
              </Button>
            </div>
            <p className="text-[11px] text-amber-700/80">Accepted formats: PDF, JPEG, PNG (Max 10MB)</p>
          </div>
        )}

        {/* ── 4. Institutional Verification Notice ── */}
        <div className="p-4 rounded-xl border border-slate-200 bg-slate-50/60 flex items-start gap-3 text-xs text-slate-600">
          <Building2 className="w-4 h-4 text-slate-400 shrink-0 mt-0.5" />
          <p className="leading-relaxed">
            Partner universities and EMGS visa officers can verify your accreditation directly using your Certificate Number ({certNumber || 'QS-AGT'}). For formal representation letters or verification inquiries, contact your assigned Account Manager.
          </p>
        </div>
      </div>
    </div>
  );
};

export default AgentAgreementSettings;
